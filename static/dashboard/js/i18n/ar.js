/* D122: the one phrase resolver for DATA strings shown in Arabic (E.ph).
   Whole-phrase entries win; otherwise month and weekday abbreviations
   inside a date ("Aug 15, 09:40", "12 Aug", "Sun 14:00") translate token
   by token, day before month. Codes and numbers pass through. */
window.EKO_I18N.phrase = function(s){
  const P = window.EKO_I18N.paramAr; if(typeof s !== 'string') return s; if(P[s]) return P[s];
  const AGO = { s: 'ث', m: 'د', h: 'س', d: 'ي' };   /* "2 s ago" → "قبل 2 ث" (heartbeats and ages carried as data) */
  const pts = s.match(/^([\d,]+) points$/); if(pts) return pts[1] + ' نقطة';   /* "4,812 points" (integration point counts carried as data) */
  const ago = s.match(/^(\d+) ([smhd]) ago$/); if(ago) return 'قبل ' + ago[1] + ' ' + AGO[ago[2]];
  const MON = /\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, DAY = /\b(Sun|Mon|Tue|Wed|Thu|Fri|Sat)\b/g;
  return s.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2})\b/g, (m, mo, d) => d + ' ' + P[mo]).replace(MON, m => P[m] || m).replace(DAY, m => P[m] || m);
};

