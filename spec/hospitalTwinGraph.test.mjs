test('failure propagation, power: the ATS stops everything it powers; an SMDB its own floor; an MCC its plant; a DB its rooms', () => {
  const all = poweredBy(ATS)
  assert.deepEqual(fails(G, ATS), [ATS, ...all].sort(), 'ATS: the MDB, every board and every powered item, and nothing else')
  assert.equal(all.length, T.EQUIP.length - 4, 'every item but DEWA, the generator, the weather sensor and the ATS itself')
  assert.ok(!fails(G, ATS).some(id => ['DEWA_SUPPLY', 'GENERATOR', 'WEATHER'].includes(id)))
  for (const n of [1, 2, 3]) {
    const sm = 'SMDB_0' + n, f = fails(G, sm)
    assert.ok(poweredBy(sm).every(id => f.includes(id)), sm + ' stops what it feeds')
    assert.ok(f.every(id => level(id) === 'L' + n), sm + ' stops nothing on another floor')
  }
  assert.deepEqual(fails(G, 'SMDB_04'), ['SMDB_04', 'MCC_04', 'BTU_01', 'BOILER_01', 'CHILLED_WATER_PUMP_01', 'CHILLER_01', 'CONDENSER_WATER_PUMP_01', 'COOLING_TOWER_01'].sort())
  assert.deepEqual(fails(G, 'MCC_04'), fails(G, 'SMDB_04').filter(id => id !== 'SMDB_04'), 'the MCC stops the same plant, not its own SMDB')
  const db2 = fails(G, 'DB_02')
  for (const id of ['FCU_03', 'FCU_04', 'VAV_06', 'VAV_10', 'EXHAUST_FAN_03', 'CCTV_04', 'Laser System', 'Ultrasound', 'Refrigerator with Freezer']) assert.ok(db2.includes(id), id)
  assert.ok(!db2.includes('AHU_02') && !db2.includes('FAHU_02'), 'the air handlers are on the MCC, not the DB')
  const sm2 = G.downstream('SMDB_02')
  assert.equal(Object.entries(sm2).filter(([id, v]) => level(id) !== 'L2' && v.state === 'fail').length, 0)
  assert.ok(Object.keys(sm2).some(id => level(id) === 'RF'), 'but the roof plant sees the change in coil demand')
})

