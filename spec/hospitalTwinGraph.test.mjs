const level = id => T.EQUIP.find(e => e.id === id).level
const feed = (list = EQ) => list.map(e => ({ id: e.name, finId: e.finId, bimId: e.bimId, floor: e.floor, tags: e.tags, typeEn: String(e.type).toUpperCase(), st: 'ok', points: e.points }))
/* as data-map.js mapAlarm keeps an alarm: FIN's severity word and priority as sent, its earlier records as hist */
const dashAlarms = () => ALARMS.map(a => ({ id: a.id, sourceId: a.source_id, state: a.state, plainEn: a.message, techEn: a.detail, sev: a.severity,
  finSeverity: a.severity, priority: a.priority, locEn: a.source, hist: a.history.map(h => ({ open: h.open })) }))
const resolveAll = (assets, connected = true) => { const idx = M.index(assets); return Object.fromEntries(T.EQUIP.map(e => [e.id, M.resolve(e, idx, connected)])) }
const states = r => Object.fromEntries(Object.entries(r).map(([k, v]) => [k, v.state + (v.weak ? '-weak' : '')]))

/* ── Phase 4: the relationship graph on the V2 design ── */
const key = l => l.from + '>' + l.to + '>' + l.kind + '>' + l.what
const withNotes = links => links.flatMap(l => [key(l), ...l.also.map(a => key({ ...l, ...a }))])
const feedChain = id => { const out = []; for (let e = T.EQUIP.find(x => x.id === id); e && e.feed; e = T.EQUIP.find(x => x.id === e.feed)) out.push(e.feed); return out }
const poweredBy = id => T.EQUIP.filter(e => feedChain(e.id).includes(id)).map(e => e.id)
const fails = (g, id) => Object.entries(g.downstream(id)).filter(([, v]) => v.state === 'fail').map(([k]) => k).sort()
/* the client's own downstream(), run on its own list: the oracle the Studio graph must agree with */
const v2Down = seed => {
  const res = { [seed]: { state: 'fail', step: 0, weak: false } }, q = [seed]
  while (q.length) {
    const cur = q.shift(), here = res[cur]
    V2L.forEach(l => {
      if (l.from !== cur) return
      const p = res[l.to]
      if (l.kind === 'stop' && here.state === 'fail') { if (p && p.state === 'fail') return; res[l.to] = { state: 'fail', step: here.step + 1, weak: false }; q.push(l.to) }
      else if (!p) { res[l.to] = { state: 'warn', step: here.step + 1, weak: !l.prop }; if (l.prop) q.push(l.to) }
    })
  }
  return res
}

